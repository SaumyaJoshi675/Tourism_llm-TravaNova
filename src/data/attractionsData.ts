// Helper function to get attractions by category
export const getAttractionsByCategory = (category: string): Attraction[] => {
    return sampleAttractions.filter(a => a.category === category);
};

// Helper function to get top-rated attractions
export const getTopRatedAttractions = (limit: number = 5): Attraction[] => {
    return [...sampleAttractions]
        .sort((a, b) => b.rating - a.rating)
        .slice(0, limit);
};

// Helper function to get most popular attractions
export const getMostPopularAttractions = (limit: number = 5): Attraction[] => {
    return [...sampleAttractions]
        .sort((a, b) => (b.popularity || 0) - (a.popularity || 0))
        .slice(0, limit);
};
